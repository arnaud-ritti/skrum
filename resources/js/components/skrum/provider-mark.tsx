const multicolourMarks: Record<string, (props: MarkProps) => ReactElement> = {
    slack: SlackMark,
    msteams: MicrosoftTeamsMark,
    entra: MicrosoftMark,
};

/**
 * The logo of an integration or sign-in provider, beside its name: hidden
 * from assistive tech, the name says it. A provider without a mark gets the
 * first letter of its label.
 */
export function ProviderMark({
    provider,
    label,
    className,
}: {
    provider: string;
    label?: string;
    className?: string;
}): ReactElement {
    const key = aliases[provider] ?? provider;
    const classes = cn('size-4 shrink-0', className);
    const Multicolour = multicolourMarks[key];
    const Generic = genericMarks[key];
    const monochrome = monochromeMarks[key];

    if (Multicolour !== undefined) {
        return <Multicolour className={classes} />;
    }

    if (Generic !== undefined) {
        return (
            <Generic
                aria-hidden="true"
                data-provider-mark={key}
                className={classes}
            />
        );
    }

    if (monochrome === undefined) {
        return (
            <span
                aria-hidden="true"
                data-provider-mark="letter"
                className={cn(
                    'text-center font-display text-base/none font-extrabold',
                    classes,
                )}
            >
                {(label ?? provider).charAt(0).toUpperCase()}
            </span>
        );
    }

    return (
        <svg
            viewBox="0 0 24 24"
            aria-hidden="true"
            fill={monochrome.color}
            data-provider-mark={key}
            className={classes}
        >
            <path d={monochrome.path} />
        </svg>
    );
}
